class RandomFlipHorizontal(Transform):
    def __init__(self, p = 0.5):
        self.p = p

    def __call__(self, img):
        """
        Horizonally flip an image, specified as an H x W x C NDArray.
        Args:
            img: H x W x C NDArray of an image
        Returns:
            H x W x C NDArray corresponding to image flipped with probability self.p
        Note: use the provided code to provide randomness, for easier testing
        """
        flip_img = np.random.rand() < self.p
        ### BEGIN YOUR SOLUTION
        if flip_img:
            # reverse the W axis
            return img[:, ::-1, :]
        return img
        ### END YOUR SOLUTION


class RandomCrop(Transform):
    def __init__(self, padding=3):
        self.padding = padding

    def __call__(self, img):
        """ Zero pad and then randomly crop an image.
        Args:
             img: H x W x C NDArray of an image
        Return 
            H x W x C NDArray of cliped image
        Note: generate the image shifted by shift_x, shift_y specified below
        """
        shift_x, shift_y = np.random.randint(low=-self.padding, high=self.padding+1, size=2)
        ### BEGIN YOUR SOLUTION
        H, W, C = img.shape
        pad = self.padding
        padded = np.zeros((H + 2 * pad, W + 2 * pad, C), dtype=img.dtype)
        padded[pad:pad + H, pad:pad + W, :] = img
        # the window starts at the centered position offset by the shift, so a
        # large enough shift can slide the image entirely out of frame
        start_x = pad + shift_x
        start_y = pad + shift_y
        return padded[start_x:start_x + H, start_y:start_y + W, :]
        ### END YOUR SOLUTION
